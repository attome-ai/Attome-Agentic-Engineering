"""I2: the REST door to the engine. Every MCP tool is also POST /api/tools/<name>, with the same JSON schema and the same
code behind it, so nothing can be done through one door and not the other. Study progress is a server-sent event stream.

  python -m structura.app.rest [--port 8765]      serve (local only)
  python -m structura.app.rest --docs             regenerate docs/api.md from the schemas

GET  /openapi.json                     OpenAPI 3.1, generated from the tool schemas
GET  /api/tools                        tool names and descriptions
POST /api/tools/<name>                 call a tool; body = its JSON arguments
GET  /api/studies/<id>/events          server-sent events: every timeline step, then each new one (?once=1 stops at the end)
GET  /api/studies/<id>/evaluations     every evaluation from trial number ?from=N on (the live Pareto chart polls this)
GET  /studies/<id>/report              the study's report, from this origin, so its Pareto chart can steer the search

Local only: a request whose Host is not this machine is refused, and so is a POST from another origin, so a web page the
user happens to have open cannot reach the tools.
"""
from __future__ import annotations

import argparse
import json
import re
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

import anyio
import mcp as mcp_sdk

from structura.agent import mcp_server as srv
from structura.agent import studies as S
from structura.optimize import pareto

ROOT = Path(__file__).resolve().parents[2]
_tools_cache: list | None = None


def tools() -> list:
    global _tools_cache
    if _tools_cache is None:
        async def go():
            async with mcp_sdk.Client(srv.mcp) as c:
                return (await c.list_tools()).tools
        _tools_cache = anyio.run(go)
    return _tools_cache


def call_tool(name: str, args: dict):
    async def go():
        async with mcp_sdk.Client(srv.mcp) as c:
            return await c.call_tool(name, args)
    r = anyio.run(go)
    if getattr(r, "is_error", False):
        raise ValueError("".join(getattr(x, "text", "") for x in r.content) or f"tool {name} failed")
    if r.structured_content is not None:
        out = r.structured_content
        return out.get("result", out) if set(out) == {"result"} else out
    text = "".join(getattr(x, "text", "") for x in r.content)
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return {"text": text}


def openapi() -> dict:
    paths = {}
    for t in tools():
        paths[f"/api/tools/{t.name}"] = {"post": {
            "operationId": t.name, "summary": t.description.split(". ")[0][:120], "description": t.description,
            "requestBody": {"required": True, "content": {"application/json": {"schema": t.input_schema}}},
            "responses": {"200": {"description": "the tool's JSON result; a failed step has ok: false with a typed error and a repair playbook"}}}}
    paths["/api/studies/{study_id}/events"] = {"get": {
        "operationId": "study_events", "summary": "Server-sent events: every step in the study's timeline, then new ones as they happen",
        "parameters": [{"name": "study_id", "in": "path", "required": True, "schema": {"type": "string"}},
                       {"name": "once", "in": "query", "schema": {"type": "integer"}, "description": "1 = stop at the end of the current timeline"}],
        "responses": {"200": {"description": "text/event-stream of step events"}}}}
    paths["/api/studies/{study_id}/evaluations"] = {"get": {
        "operationId": "study_evaluations", "summary": "Every evaluation of the study from a trial number on, with its metrics and whether it was steered",
        "parameters": [{"name": "study_id", "in": "path", "required": True, "schema": {"type": "string"}},
                       {"name": "from", "in": "query", "schema": {"type": "integer"}, "description": "first trial number to return (default 0)"}],
        "responses": {"200": {"description": "{ok, rows}"}, "404": {"description": "no optimization has run yet"}}}}
    paths["/studies/{study_id}/report"] = {"get": {
        "operationId": "study_report", "summary": "The study's report page; served from here, its Pareto chart can steer the search and its timeline follows the study",
        "parameters": [{"name": "study_id", "in": "path", "required": True, "schema": {"type": "string"}}],
        "responses": {"200": {"description": "text/html"}, "404": {"description": "no report built yet"}}}}
    return {"openapi": "3.1.0", "info": {"title": "Attome Agentic Engineering", "version": "0.1.0"},
            "servers": [{"url": "http://127.0.0.1:8765"}], "paths": paths}


EXAMPLES = {"list_families": "{}", "derive_load": '{"mass_kg": 20}', "describe_grammar": "{}", "get_job": '{"job_id": "<from run_optimization>"}'}


def api_markdown() -> str:
    lines = ["# API", "", "Generated by `python -m structura.app.rest --docs` from the tool schemas; do not edit by hand.", "",
             "Four doors, one engine:", "",
             "| Door | Start | Use |", "|---|---|---|",
             "| MCP | `python -m structura.agent.mcp_server` | any MCP client (Claude Code, Claude Desktop) |",
             "| REST | `python -m structura.app.rest` | scripts and other programs; `GET /openapi.json` |",
             "| Python | `from structura import Study` | notebooks |",
             "| CLI | `python -m structura.cli run spec.json --accept` | batch runs and CI |", "",
             "## REST example", "", "```", "curl -X POST http://127.0.0.1:8765/api/tools/derive_load -H \"Content-Type: application/json\" -d '{\"mass_kg\": 20}'", "```", "",
             "## Python example", "", "```python", "from structura import Study", "study = Study.from_spec(\"docs/examples/bracket_20kg.json\")",
             "study.accept(\"me\")", "study.optimize(budget=120)", "best = study.recommended()", "print(study.verify(best[\"params\"])[\"grade\"])",
             "print(study.report())", "```", "", "## CLI example", "", "```", "python -m structura.cli run docs/examples/bracket_20kg.json --accept --budget 120 --out runs/my_study", "```", "",
             "## Tools", ""]
    for t in sorted(tools(), key=lambda t: t.name):
        props = t.input_schema.get("properties", {})
        required = set(t.input_schema.get("required", []))
        lines += [f"### {t.name}", "", t.description, ""]
        if props:
            lines += ["| Argument | Type | Required |", "|---|---|---|"]
            for k, p in props.items():
                kind = p.get("type") or " or ".join(x.get("type", "?") for x in p.get("anyOf", []))
                lines.append(f"| `{k}` | {kind} | {'yes' if k in required else 'no'} |")
            lines.append("")
        if t.name in EXAMPLES:
            lines += [f"Example body: `{EXAMPLES[t.name]}`", ""]
    return "\n".join(lines) + "\n"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):  # quiet
        pass

    def _json(self, obj, code: int = 200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _events(self, study_id: str, once: bool):
        try:
            S.folder(study_id)
        except ValueError as e:
            return self._json({"ok": False, "error": "study", "message": str(e)}, 400)
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "close")
        self.end_headers()
        self.close_connection = True
        sent = 0
        try:
            while True:
                rows = S.timeline(study_id)
                for e in rows[sent:]:
                    self.wfile.write(f"event: step\ndata: {json.dumps(e)}\n\n".encode())
                sent = len(rows)
                self.wfile.flush()
                if once:
                    self.wfile.write(b"event: end\ndata: {}\n\n")
                    return
                time.sleep(0.5)
        except (BrokenPipeError, ConnectionError):
            return

    def _local_only(self) -> bool:
        host = (self.headers.get("Host") or "").rsplit(":", 1)[0]
        origin = self.headers.get("Origin")
        if host not in ("127.0.0.1", "localhost") or (self.command == "POST" and origin and urlparse(origin).netloc != self.headers.get("Host")):
            self.close_connection = True
            self._json({"ok": False, "error": "forbidden", "message": "this server answers only this machine's own pages"}, 403)
            return False
        return True

    def _report(self, study_id: str):
        try:
            p = S.folder(study_id) / "report.html"
        except ValueError as e:
            return self._json({"ok": False, "error": "study", "message": str(e)}, 400)
        if not p.exists():
            return self._json({"ok": False, "error": "results", "message": "this study has no report yet; call build_report"}, 404)
        body = p.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _evaluations(self, study_id: str, start: int):
        try:
            study = srv._study(study_id)
        except ValueError as e:
            return self._json({"ok": False, "error": "study", "message": str(e)}, 400)
        if study is None:
            return self._json({"ok": False, "error": "results", "message": "run an optimization first"}, 404)
        return self._json({"ok": True, "rows": pareto.history_rows(study, start)})

    def do_GET(self):
        if not self._local_only():
            return
        u = urlparse(self.path)
        if u.path == "/openapi.json":
            return self._json(openapi())
        if u.path == "/api/tools":
            return self._json([{"name": t.name, "description": t.description} for t in tools()])
        m = re.fullmatch(r"/api/studies/([^/]+)/events", u.path)
        if m:
            return self._events(m.group(1), parse_qs(u.query).get("once", ["0"])[0] == "1")
        m = re.fullmatch(r"/api/studies/([^/]+)/evaluations", u.path)
        if m:
            return self._evaluations(m.group(1), int(parse_qs(u.query).get("from", ["0"])[0]))
        m = re.fullmatch(r"/studies/([^/]+)/report", u.path)
        if m:
            return self._report(m.group(1))
        self._json({"ok": False, "error": "not_found", "message": f"no such path {u.path}"}, 404)

    def do_POST(self):
        if not self._local_only():
            return
        u = urlparse(self.path)
        m = re.fullmatch(r"/api/tools/([a-z_]+)", u.path)
        if not m or m.group(1) not in {t.name for t in tools()}:
            return self._json({"ok": False, "error": "not_found", "message": f"no such tool path {u.path}"}, 404)
        try:
            args = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))) or b"{}")
        except json.JSONDecodeError as e:
            return self._json({"ok": False, "error": "bad_json", "message": str(e)}, 400)
        if not isinstance(args, dict):
            return self._json({"ok": False, "error": "bad_json", "message": "the body must be a JSON object of arguments"}, 400)
        try:
            return self._json(call_tool(m.group(1), args))
        except Exception as e:  # noqa: BLE001 - an invalid argument comes back as a typed error, not a dropped connection
            return self._json({"ok": False, "error": "tool", "message": str(e)}, 400)


def serve(port: int = 8765) -> ThreadingHTTPServer:
    tools()  # discover once, before any request
    return ThreadingHTTPServer(("127.0.0.1", port), Handler)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--docs", action="store_true", help="regenerate docs/api.md and exit")
    a = ap.parse_args()
    if a.docs:
        (ROOT / "docs" / "api.md").write_text(api_markdown(), encoding="utf-8", newline="\n")
        print("wrote docs/api.md")
        return
    print(f"http://127.0.0.1:{a.port}/openapi.json", flush=True)
    serve(a.port).serve_forever()


if __name__ == "__main__":
    main()
