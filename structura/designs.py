"""A Design: a family graph plus parameter values, with a stable content hash.

The hash covers the canonical graph JSON and the parameters rounded to 6 significant digits, so equal designs
hash equally across runs and machines and any change gives a new hash.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from structura.grammar.compile import CompiledPart, compile_graph
from structura.grammar.graph import DesignGraph


def _round(v: float) -> float:
    return float(f"{v:.6g}")


@dataclass
class Design:
    graph: DesignGraph
    params: dict[str, float]
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat(timespec="seconds"))

    def __post_init__(self):
        self.params = {k: _round(float(v)) for k, v in self.graph.values(self.params).items()}

    @property
    def template(self) -> str:
        return self.graph.name

    @property
    def template_version(self) -> str:
        return self.graph.version

    @property
    def hash(self) -> str:
        payload = json.dumps({"graph": json.loads(self.graph.canonical_json()),
                              "params": dict(sorted(self.params.items()))}, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def build(self) -> CompiledPart:
        return compile_graph(self.graph, self.params)

    def script(self) -> str:
        """A standalone Python script that rebuilds this design with structura (graph and params embedded)."""
        return (
            "# Generated by Attome AE. Rebuilds the design from its graph and parameters.\n"
            "import json\n"
            "from structura.grammar.graph import DesignGraph\n"
            "from structura.grammar.compile import compile_graph\n\n"
            f"GRAPH = json.loads({self.graph.canonical_json()!r})\n"
            f"PARAMS = {json.dumps(self.params, sort_keys=True)}\n\n"
            "part = compile_graph(DesignGraph.model_validate(GRAPH), PARAMS)\n"
            "shape = part.shape\n"
        )

    def save(self, folder: str | Path) -> Path:
        d = Path(folder)
        d.mkdir(parents=True, exist_ok=True)
        (d / "graph.json").write_text(json.dumps(self.graph.model_dump(mode="json"), indent=2), encoding="utf-8")
        (d / "params.json").write_text(json.dumps({"template": self.template, "template_version": self.template_version,
                                                   "params": self.params, "created_at": self.created_at,
                                                   "hash": self.hash}, indent=2), encoding="utf-8")
        (d / "design.py").write_text(self.script(), encoding="utf-8")
        return d

    @classmethod
    def load(cls, folder: str | Path) -> "Design":
        d = Path(folder)
        graph = DesignGraph.model_validate(json.loads((d / "graph.json").read_text(encoding="utf-8")))
        meta = json.loads((d / "params.json").read_text(encoding="utf-8"))
        out = cls(graph, meta["params"], meta["created_at"])
        if out.hash != meta["hash"]:
            raise ValueError(f"design in {d} does not match its stored hash")
        return out
